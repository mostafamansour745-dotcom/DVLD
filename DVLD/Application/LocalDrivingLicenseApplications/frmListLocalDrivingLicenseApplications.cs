        private void cmsApplications_Opening(object sender, CancelEventArgs e)
        {
            if (dgvLocalDrivingLicenseApplications.CurrentRow == null)
                return;

            int LocalDrivingLicenseApplicationID = (int)dgvLocalDrivingLicenseApplications.CurrentRow.Cells[0].Value;
            int PassedTests = Convert.ToInt32(dgvLocalDrivingLicenseApplications.CurrentRow.Cells[5].Value);

            bool IsPassedAllTests = (PassedTests == 3);

            ScheduleTestsMenue.Enabled = !IsPassedAllTests;

            if (ScheduleTestsMenue.Enabled)
            {

                scheduleVisionTestToolStripMenuItem.Enabled = (PassedTests == 0);


                scheduleWrittenTestToolStripMenuItem.Enabled = (PassedTests == 1);


                scheduleStreetTestToolStripMenuItem.Enabled = (PassedTests == 2);
            }


            issueDrivingLicenseFirstTimeToolStripMenuItem.Enabled = IsPassedAllTests;
        }

